#!/usr/bin/env node
// Writes typed ABIs and deployment addresses into frontend/ and backend/.
// Run after `forge build`. Output is TypeScript with `as const`, because JSON imports lose ABI types.
// Usage: node scripts/sync-abi.mjs [ContractName ...]

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = process.argv.length > 2 ? process.argv.slice(2) : ['UpfrontAccess', 'Upfront', 'InvestorGate'];
const targets = ['frontend/src/generated', 'backend/src/generated'];
const header = '// Generated by scripts/sync-abi.mjs. Do not edit.\n\n';

const toConst = (name) => `${name[0].toLowerCase()}${name.slice(1)}Abi`;

const abis = names.flatMap((name) => {
  const artifact = join(root, 'contracts/out', `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact)) {
    console.warn(`skipped ${name}: no artifact, run forge build if it should exist`);
    return [];
  }
  const { abi } = JSON.parse(readFileSync(artifact, 'utf8'));
  return [`export const ${toConst(name)} = ${JSON.stringify(abi, null, 2)} as const;\n`];
});

const deployments = JSON.parse(readFileSync(join(root, 'deployments.json'), 'utf8'));

for (const target of targets) {
  const dir = join(root, target);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'abis.ts'), header + (abis.join('\n') || 'export {};\n'));
  writeFileSync(
    join(dir, 'deployments.ts'),
    `${header}export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
  );
  console.log(`wrote ${target}`);
}
